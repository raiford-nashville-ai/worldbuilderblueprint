import { KEYS, QUESTIONS } from './generate.js';

const markdownQuote = text => text.split('\n').map(line => `> ${line}`).join('\n');
const yamlString = text => JSON.stringify(text);
export function blueprintToMarkdown(blueprint) {
  const p = blueprint.profile;
  const lines = [
    '---',
    `title: ${yamlString(blueprint.title)}`,
    `description: ${yamlString(blueprint.description)}`,
    `created: ${yamlString(blueprint.createdISO)}`,
    'document_type: "Authoring Kit · World Notes"',
    'edition: "First expression"',
    'generator: "Phase One local mock"',
    '---', '',
    `# ${blueprint.title}`, '',
    `*${blueprint.description}*`, '',
    blueprint.opening, ''
  ];
  blueprint.sections.forEach(section => {
    lines.push(`## ${section.heading}`, '');
    section.paragraphs.forEach(text => lines.push(text, ''));
    section.quotations.forEach(quote => lines.push(`**${quote.label}**`, '', markdownQuote(quote.text), ''));
  });
  if (blueprint.openThreads.length) {
    lines.push('## Doors left open', '', 'Return to these questions only when they help.', '');
    blueprint.openThreads.forEach(item => lines.push(`- **${item.label}:** ${item.question}`));
    lines.push('');
  }
  lines.push('---', '', '## Source material', '', '### Your original Spark', '', p.spark, '', '### Discovery responses', '');
  KEYS.forEach(key => { if (p.answers[key]) lines.push(`#### ${key.charAt(0).toUpperCase() + key.slice(1)} — ${QUESTIONS[key]}`, '', p.answers[key], ''); });
  lines.push('*This Blueprint is a local Phase One demonstration; it was not generated by an AI service.*', '');
  return lines.join('\n');
}

// Owns clipboard fallback nodes and download URLs. The caller supplies the
// current document on each click, so editing/regeneration never exports stale data.
export function initExport(root, getBlueprint) {
  const status = root.querySelector('#exportStatus');
  root.querySelector('#copyButton').addEventListener('click', async () => {
    const blueprint = getBlueprint();
    if (!blueprint) return;
    try {
      const markdown = blueprintToMarkdown(blueprint);
      if (navigator.clipboard?.writeText) await navigator.clipboard.writeText(markdown);
      else {
        const previousFocus = document.activeElement;
        const hiddenField = document.createElement('textarea');
        hiddenField.value = markdown;
        hiddenField.style.cssText = 'position:fixed;left:-9999px;top:0';
        document.body.append(hiddenField);
        try {
          hiddenField.select();
          if (!document.execCommand('copy')) throw new Error('Clipboard unavailable');
        } finally {
          hiddenField.remove();
          previousFocus?.focus({ preventScroll: true });
        }
      }
      status.textContent = 'Markdown copied to your clipboard.';
    } catch (_) { status.textContent = 'Your browser could not copy automatically. Try Download .md instead.'; }
  });
  root.querySelector('#downloadButton').addEventListener('click', () => {
    const blueprint = getBlueprint();
    if (!blueprint) return;
    const blob = new Blob([blueprintToMarkdown(blueprint)], { type: 'text/markdown;charset=utf-8' });
    const objectURL = URL.createObjectURL(blob);
    const link = document.createElement('a');
    const safeName = blueprint.title.toLowerCase().normalize('NFKD').replace(/[^a-z0-9\s-]/g, '').trim().replace(/\s+/g, '-').slice(0, 50) || 'my-world-blueprint';
    link.href = objectURL;
    link.download = `${safeName}-blueprint.md`;
    document.body.append(link);
    try { link.click(); }
    finally {
      link.remove();
      setTimeout(() => URL.revokeObjectURL(objectURL), 1000);
    }
    status.textContent = 'Your Markdown file is ready.';
  });
  return { clearStatus: () => { status.textContent = ''; } };
}
